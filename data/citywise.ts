export function getCitywiseBySlug(slug: string): CitywiseItem | undefined {
  const raw = slug.toLowerCase().trim();

  // Helper to normalize alternate spellings and hyphens
  const canonicalize = (s: string) =>
    s
      .replace(/^in-/, "")
      .replace(/chennia/g, "chennai")
      .replace(/jhasi/g, "jhansi")
      .replace(/[^a-z0-9]/g, "");

  const canonicalRaw = canonicalize(raw);

  // 1. Direct exact match on slug or id
  const direct = citywiseItems.find(
    (item) => item.slug.toLowerCase() === raw || item.id.toLowerCase() === raw
  );
  if (direct) return direct;

  // 2. Match with or without "in-" prefix
  const rawWithoutIn = raw.replace(/^in-/, "");
  const inPrefixMatch = citywiseItems.find((item) => {
    const itemWithoutIn = item.slug.toLowerCase().replace(/^in-/, "");
    const itemIdWithoutIn = item.id.toLowerCase().replace(/^in-/, "");
    return (
      itemWithoutIn === rawWithoutIn ||
      itemIdWithoutIn === rawWithoutIn ||
      `in-${item.slug.toLowerCase()}` === raw ||
      item.slug.toLowerCase() === `in-${raw}`
    );
  });
  if (inPrefixMatch) return inPrefixMatch;

  // 3. Canonicalized match (handles spelling quirks like chennia <-> chennai, jhasi <-> jhansi)
  return citywiseItems.find((item) => {
    const itemCanonicalSlug = canonicalize(item.slug);
    const itemCanonicalId = canonicalize(item.id);
    return itemCanonicalSlug === canonicalRaw || itemCanonicalId === canonicalRaw;
  });
}

